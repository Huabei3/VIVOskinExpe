function duv=Duv(white)
X=white(1);
Y=white(2);
Z=white(3);
x=X/(X+Y+Z);
y=Y/(X+Y+Z);
u=4*x/(-2*x+12*y+3);
v=6*y/(-2*x+12*y+3);
k6=-0.00616793;
k5=0.0893944;
k4=-0.5179722;
k3=1.5317403;
k2=-2.4243787;
k1=1.925865;
k0=-0.471106;
lfp=((u-0.292)^2+(v-0.24)^2)^0.5;
a=acos((u-0.292)/lfp);
lbb=k6*a^6+k5*a^5+k4*a^4+k3*a^3+k2*a^2+k1*a+k0;
duv=lfp-lbb;
